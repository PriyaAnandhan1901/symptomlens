const express = require('express');
const cors = require('cors');
const pool = require('./db');
pool.query('SELECT NOW()').then(r => console.log('DB OK:', r.rows[0])).catch(e => console.log('DB ERROR:', e.message));
const authRoutes = require('./auth');

console.log('DATABASE_URL:', process.env.DATABASE_URL);
console.log('DB_PASSWORD:', process.env.DB_PASSWORD);

const app = express();
app.use(cors({
  origin: [
    'http://localhost:5173',
    'https://symptomlens.vercel.app',
    'https://symptomlens-g6oozczy6-priyaanandan682-7674s-projects.vercel.app'
  ],
  credentials: true
}));
app.use(express.json());

app.use('/auth', authRoutes);

app.get('/', (req, res) => {
  res.json({ message: 'SymptomLens API is running!' });
});

app.post('/symptoms', async (req, res) => {
  try {
    const { user_id, symptom_name, severity, notes } = req.body;
    const result = await pool.query(
      'INSERT INTO symptoms (user_id, symptom_name, severity, notes) VALUES ($1, $2, $3, $4) RETURNING *',
      [user_id, symptom_name, severity, notes]
    );
    res.json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

app.get('/symptoms', async (req, res) => {
  try {
    const result = await pool.query(
      'SELECT * FROM symptoms ORDER BY logged_at DESC'
    );
    res.json(result.rows);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

